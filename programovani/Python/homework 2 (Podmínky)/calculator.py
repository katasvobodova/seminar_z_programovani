number_one = int(input("please write some number"))
number_two = int(input("please write some number"))
number_operation = (input("please write some number operation (+, -, *, /)"))
if number_operation == "+":
    print(number_one+number_two)
elif number_operation == "-":
    print(number_one-number_two)
elif number_operation == "*":
    print(number_one*number_two)
else:
    print(number_one/number_two)



